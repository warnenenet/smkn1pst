#!/usr/bin/env bash
set -euo pipefail

SECRETS_DIR="${SECRETS_DIR:-/app/storage/secrets}"
DATA_ROOT="${DATA_DIR:-/app/data}"
STORAGE_ROOT="${WA_STORAGE_DIR:-/app/storage}"

mkdir -p \
  "$SECRETS_DIR" \
  "$STORAGE_ROOT/wa_gateway/baileys_auth" \
  "$STORAGE_ROOT/debug" \
  "$DATA_ROOT/snapshots" \
  "$DATA_ROOT/tts_cache" \
  "$DATA_ROOT/backups" \
  /tmp/face-engine-debug

chmod 700 "$SECRETS_DIR"

TOKEN_FILE="$SECRETS_DIR/internal_token"
if [[ ! -s "$TOKEN_FILE" ]]; then
  openssl rand -hex 48 > "$TOKEN_FILE"
fi
chmod 600 "$TOKEN_FILE"

read_sha_pin() {
  local file="$1"
  if [[ -f "$file" ]]; then
    awk '{print $1}' "$file" | tr -d '[:space:]'
  fi
}

DET_SHA="${DET_MODEL_SHA256:-$(read_sha_pin /app/models/det_10g.sha256)}"
REC_SHA="${REC_MODEL_SHA256:-$(read_sha_pin /app/models/w600k_r50.sha256)}"
ORT_SHA="${ORT_DYLIB_SHA256:-$(read_sha_pin /app/models/ort_dylib.sha256)}"

RUNTIME_ENV="$SECRETS_DIR/runtime.env"
cat > "$RUNTIME_ENV" <<EOF
# Auto-generated by entrypoint.sh (s6 init-env) — DO NOT EDIT MANUALLY
TZ="Asia/Jakarta"
NODE_ENV="production"
PORT="80"
APP_ROOT="/app"
DATA_DIR="${DATA_ROOT}"
WA_STORAGE_DIR="${STORAGE_ROOT}"
INTERNAL_TOKEN_FILE="${TOKEN_FILE}"
FACE_SERVICE_URL="http://127.0.0.1:8001"
FACE_PORT="8001"
WEB_BACKEND_URL="http://127.0.0.1:80"
WA_GATEWAY_PORT="8003"
WA_GATEWAY_AUTO_SPAWN="0"
INSIGHTFACE_HOME="/app/models/insightface"
DET_MODEL_PATH="/app/models/insightface/models/buffalo_l/det_10g.onnx"
REC_MODEL_PATH="/app/models/insightface/models/buffalo_l/w600k_r50.onnx"
ORT_DYLIB_PATH="/usr/local/lib/libonnxruntime.so"
DET_MODEL_SHA256="${DET_SHA}"
REC_MODEL_SHA256="${REC_SHA}"
ORT_DYLIB_SHA256="${ORT_SHA}"
ORT_INTRA_THREADS="${ORT_INTRA_THREADS:-2}"
MAX_CAMERA_WORKERS="${MAX_CAMERA_WORKERS:-8}"
PROCESS_EVERY_N_FRAMES="${PROCESS_EVERY_N_FRAMES:-2}"
DEBUG_TMP_DIR="/tmp/face-engine-debug"
PIPER_BIN="/usr/local/piper/piper"
PIPER_MODEL="/app/models/piper/id_ID-news_tts-medium.onnx"
EOF
chmod 600 "$RUNTIME_ENV"

set -a
# shellcheck disable=SC1090
source "$RUNTIME_ENV"
set +a

if [[ "${SKIP_BOOT_MODEL_CHECK:-0}" != "1" ]] && [[ -x /app/bin/face-engine ]]; then
  /app/bin/face-engine check-config
fi
