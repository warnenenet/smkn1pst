#!/usr/bin/env bash
set -Eeuo pipefail

SECRETS_DIR="${SECRETS_DIR:-/app/storage/secrets}"
DATA_ROOT="${DATA_DIR:-/app/data}"
STORAGE_ROOT="${WA_STORAGE_DIR:-/app/storage}"

mkdir -p \
  "$SECRETS_DIR" \
  "$STORAGE_ROOT/wa_sessions" \
  "$STORAGE_ROOT/wa_qr" \
  "$DATA_ROOT/snapshots" \
  "$DATA_ROOT/tts_cache" \
  "$DATA_ROOT/backups" \
  /var/log/supervisor

chmod 700 "$SECRETS_DIR"

TOKEN_FILE="$SECRETS_DIR/internal_token"
if [[ ! -s "$TOKEN_FILE" ]]; then
  openssl rand -hex 48 > "$TOKEN_FILE"
fi
chmod 600 "$TOKEN_FILE"

# File runtime.env dibuat otomatis untuk menjembatani variabel internal antar service di dalam container.
# BUKAN untuk diedit manusia. Token autentikasi tetap dibaca langsung dari FILE internal_token.
RUNTIME_ENV="$SECRETS_DIR/runtime.env"
cat > "$RUNTIME_ENV" <<EOF
# Auto-generated by entrypoint.sh — DO NOT EDIT MANUALLY
TZ="Asia/Jakarta"
NODE_ENV="production"
PORT="80"
DATA_DIR="${DATA_ROOT}"
WA_STORAGE_DIR="${STORAGE_ROOT}"
INTERNAL_TOKEN_FILE="${TOKEN_FILE}"
FACE_SERVICE_URL="http://127.0.0.1:8001"
WA_GATEWAY_AUTO_SPAWN="0"
INSIGHTFACE_HOME="/app/models/insightface"
RUST_ACCEL_BIN="/app/bin/face_accel"
PIPER_BIN="/usr/local/piper/piper"
PIPER_MODEL="/app/models/piper/id_ID-news_tts-medium.onnx"
CHROME_BIN="/usr/bin/chromium"
CHROMEDRIVER_BIN="/usr/bin/chromedriver"
ENABLE_XVFB_FALLBACK="1"
OMP_NUM_THREADS="4"
OPENBLAS_NUM_THREADS="4"
ORT_INTRA_OP_NUM_THREADS="4"
ORT_INTER_OP_NUM_THREADS="2"
EOF
chmod 600 "$RUNTIME_ENV"

set -a
# shellcheck disable=SC1090
source "$RUNTIME_ENV"
set +a

exec "$@"
